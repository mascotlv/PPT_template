    assert.equal((await admin.call('/admin/account', 'PATCH', payload)).status, 200);
    assert.equal((await secondSession.call('/session')).data.admin, null);
    assert.equal((await admin.call('/admin/verification')).data.expiresAt, null);
    const profile = (await f.db.setting.findUniqueOrThrow({ where: { key: 'chat-seller-profile' } })).value;
    assert.deepEqual(Object.keys(profile).sort(), ['avatar', 'nickname']);
