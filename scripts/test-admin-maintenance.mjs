    server.shop.audit = async () => { throw new Error('Simulated transaction failure'); };
    await assert.rejects(clearBusinessData(server.shop, administrator.id, randomUUID()), /Simulated transaction failure/);
    server.shop.audit = audit;
    assert.equal(await f.db.order.count(), 3); await fs.stat(fresh);
    for (const [file, hash] of hashes) assert.equal(createHash('sha256').update(await fs.readFile(file)).digest('hex'), hash);
    console.log('PASS failed business reset rolls back database and staged files');
    await clearBusinessData(server.shop, administrator.id, randomUUID());
    assert.deepEqual(await Promise.all([f.db.product.count(), f.db.category.count(), f.db.price.count(), f.db.fileVersion.count()]), counts);
    assert.equal(await f.db.order.count(), 0); assert.equal(await f.db.customer.count(), 0); assert.equal(await f.db.refund.count(), 0);
    for (const [file, hash] of hashes) assert.equal(createHash('sha256').update(await fs.readFile(file)).digest('hex'), hash);
    assert.equal((await f.db.setting.findMany({ where: { key: { startsWith: 'purchaseFile:' } } })).length, settings.length);
    console.log('PASS business reset preserves catalog, prices, historical originals, previews and current copies');
    await admin.init();
    assert.equal((await admin.call('/admin/frontend', 'PATCH', { language: 'zh', values: { hero: '配置的首页标题' } })).status, 200);
    assert.equal((await buyer.call('/session')).data.storefrontText.zh.hero, '配置的首页标题');
    assert.equal((await admin.call('/admin/frontend', 'PATCH', { language: 'en', values: { hero: 'Configured homepage' } })).status, 200);
    assert.equal((await admin.call('/admin/frontend', 'PATCH', { language: 'zh', values: {} })).status, 200);
    assert.equal((await admin.call('/admin/frontend')).data.translations.en.hero, 'Configured homepage');
    assert.equal((await admin.call('/admin/frontend', 'PATCH', { language: 'zh', values: { unknownTextKey: 'invalid' } })).status, 400);
    const secondSession = await new BrowserSession(base, f.config).init(); await secondSession.login(f.admin);
    const nextEmail = 'updated-admin@example.test', nextPassword = 'updated-admin-passphrase';
