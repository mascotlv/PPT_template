    const approve = await requestRefund();
    assert.equal((await admin.call(`/admin/refunds/${approve}/review`, 'POST', { decision: 'approve', reason: '' })).status, 201);
    await f.db.session.updateMany({ where: { adminId: administrator.id }, data: { reauthAt: new Date(Date.now() - 360000) } });
    const expired = await requestRefund();
    assert.equal((await admin.call(`/admin/refunds/${expired}/review`, 'POST', { decision: 'approve' })).status, 403);
    await admin.reauth(f.admin);
    assert.equal((await admin.call(`/admin/refunds/${expired}/review`, 'POST', { decision: 'reject', reason: '好' })).status, 201);
