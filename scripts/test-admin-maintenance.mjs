    const versions = await f.db.fileVersion.findMany(), settings = await f.db.setting.findMany({ where: { key: { startsWith: 'purchaseFile:' } } });
    const keys = [...versions.flatMap(v => [v.key, ...v.previews]), ...settings.map(s => s.value.key)];
    const hashes = new Map(await Promise.all(keys.map(async key => [storage.resolve(key), createHash('sha256').update(await fs.readFile(storage.resolve(key))).digest('hex')])));
    const counts = await Promise.all([f.db.product.count(), f.db.category.count(), f.db.price.count(), f.db.fileVersion.count()]);
    const orphan = path.join(f.config.STORAGE_ROOT, 'unused-preview.png'), fresh = path.join(f.config.STORAGE_ROOT, 'upload-in-progress.tmp');
    await fs.writeFile(orphan, 'old unused file'); await fs.writeFile(fresh, 'new upload');
    const old = new Date(Date.now() - 172800000); await fs.utimes(orphan, old, old);
    const runtime = path.dirname(f.config.STORAGE_ROOT); await fs.writeFile(path.join(runtime, 'discard.log'), 'log'); await fs.writeFile(path.join(runtime, 'retain.json'), '{}');
    const cleaned = await cleanRuntimeFiles(server.shop, runtime); assert.ok(cleaned.removedFiles >= 2);
    await assert.rejects(fs.stat(orphan)); await fs.stat(fresh); await fs.stat(path.join(runtime, 'retain.json'));
    for (const [file, hash] of hashes) assert.equal(createHash('sha256').update(await fs.readFile(file)).digest('hex'), hash);
    console.log('PASS cleanup removes unused files and preserves referenced files and new uploads');
